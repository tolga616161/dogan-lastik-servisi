  t(key, vars = {}) {
    const lang = this.lang || this.defaultLang;
    const table = this.dict[lang] || this.dict.tr;
    let s = table[key] ?? this.dict.tr[key] ?? key;
    Object.keys(vars).forEach((k) => {
      s = s.replaceAll(`{${k}}`, String(vars[k]));
    });
    return s;
  },
  detect() {
    const saved = localStorage.getItem("dls_lang");
    if (saved && this.supported.includes(saved)) return saved;
    const nav = (navigator.language || navigator.userLanguage || "tr").toLowerCase();
    const code = nav.slice(0, 2);
    return this.supported.includes(code) ? code : "en";
  },
  setLang(lang) {
    this.lang = this.supported.includes(lang) ? lang : "tr";
    localStorage.setItem("dls_lang", this.lang);
    document.documentElement.lang = this.lang;
    document.documentElement.dir = this.lang === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") return;
      el.textContent = this.t(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.textContent = this.t(el.getAttribute("data-i18n-placeholder"));
    });
    const sel = document.getElementById("lang-switch");
    if (sel) sel.value = this.lang;
    document.dispatchEvent(new CustomEvent("dls:lang", { detail: { lang: this.lang } }));
  },
  init() {
    this.setLang(this.detect());
  },
